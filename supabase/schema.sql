create table if not exists public.headsets (
  id bigint generated by default as identity primary key,
  asset_tag text not null unique,
  brand text not null,
  model text not null,
  serial_number text,
  status text not null default 'Available'
    check (status in ('Available','Issued','Defective')),
  assigned_to text,
  department text,
  notes text,
  created_at timestamptz not null default now()
);

alter table public.headsets enable row level security;

-- Prototype policy: permits public anon-key access so the starter app works
-- immediately after adding the project URL/key. This is NOT secure for production.
-- Before real deployment, replace these policies with authenticated-only policies
-- and add a sign-in flow / role-based access control.
create policy "Authenticated users can read headsets"
on public.headsets for select to anon, authenticated using (true);

create policy "Authenticated users can insert headsets"
on public.headsets for insert to anon, authenticated with check (true);

create policy "Authenticated users can update headsets"
on public.headsets for update to authenticated using (true) with check (true);

create policy "Authenticated users can delete headsets"
on public.headsets for delete to anon, authenticated using (true);
